def time_converter(time):
    t_map = {
        '00': ('12', 'a.m.'), '12': ('12', 'p.m.'),
        '01': ('1',  'a.m.'), '13': ('1',  'p.m.'),
        '02': ('2',  'a.m.'), '14': ('2',  'p.m.'),
        '03': ('3',  'a.m.'), '15': ('3',  'p.m.'),
        '04': ('4',  'a.m.'), '16': ('4',  'p.m.'),
        '05': ('5',  'a.m.'), '17': ('5',  'p.m.'),
        '06': ('6',  'a.m.'), '18': ('6',  'p.m.'),
        '07': ('7',  'a.m.'), '19': ('7',  'p.m.'),
        '08': ('8',  'a.m.'), '20': ('8',  'p.m.'),
        '09': ('9',  'a.m.'), '21': ('9',  'p.m.'),
        '10': ('10', 'a.m.'), '22': ('10', 'p.m.'),
        '11': ('11', 'a.m.'), '23': ('11', 'p.m.')
    }
    hour, minute = time.split(':')
    return f'{t_map[hour][0]}:{minute} {t_map[hour][1]}'
